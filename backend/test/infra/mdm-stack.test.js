test('E2E: Scenario: Role policy is scoped to the table and the one secret', async (t) => {
  // Given the Lambda execution role policy
  const { template } = createTestStack();

  // Find the inline policy statements
  const iamPolicies = template.findResources('AWS::IAM::Policy');
  const inlinePolicyStatements = [];

  if (Object.keys(iamPolicies).length > 0) {
    const policyValue = Object.values(iamPolicies)[0];
    inlinePolicyStatements.push(...(policyValue.Properties.PolicyDocument.Statement || []));
  }

  // Then every DynamoDB statement names the table ARN or its index ARN
  const dynamoDbStatements = inlinePolicyStatements.filter(s =>
    s.Action && (
      (typeof s.Action === 'string' && s.Action.startsWith('dynamodb:')) ||
      (Array.isArray(s.Action) && s.Action.some(a => a.startsWith('dynamodb:')))
    )
  );

  assert.ok(dynamoDbStatements.length > 0, 'Should have at least one DynamoDB statement');

  // And exactly one statement allows secretsmanager:GetSecretValue on the pepper secret Ref
  const secretStatements = inlinePolicyStatements.filter(s =>
    s.Action && (
      (typeof s.Action === 'string' && s.Action === 'secretsmanager:GetSecretValue') ||
      (Array.isArray(s.Action) && s.Action.includes('secretsmanager:GetSecretValue'))
    )
  );

  assert.strictEqual(secretStatements.length, 1, `Should have exactly one secretsmanager:GetSecretValue statement, found ${secretStatements.length}`);

  // And no statement uses Resource "*" and no statement names another service
  for (const stmt of inlinePolicyStatements) {
    const resources = Array.isArray(stmt.Resource) ? stmt.Resource : [stmt.Resource];
    assert.ok(
      !resources.includes('*'),
      `No statement should use Resource "*"`
    );

    // Check that only DynamoDB and SecretsManager are mentioned
    const actions = Array.isArray(stmt.Action) ? stmt.Action : [stmt.Action];
    for (const action of actions) {
      const service = action.split(':')[0];
      assert.ok(
        ['dynamodb', 'secretsmanager'].includes(service),
        `Only dynamodb and secretsmanager services allowed, found: ${service}`
      );
    }
  }
});

